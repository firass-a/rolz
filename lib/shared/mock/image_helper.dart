int _stableHash(String seed) {
  var hash = 0;
  for (var i = 0; i < seed.length; i++) {
    hash = 0x1fffffff & (hash + seed.codeUnitAt(i));
    hash = 0x1fffffff & (hash + ((0x0007ffff & hash) << 10));
    hash ^= hash >> 6;
  }
  hash = 0x1fffffff & (hash + ((0x03ffffff & hash) << 3));
  hash ^= hash >> 11;
  return (hash + ((0x00003fff & hash) << 15)) & 0x1fffffff;
}

/// Portrait headshot. Pass [female] when known so gender matches the talent.
String portraitUrl(String seed, {bool? female}) {
  final pool = female == true
      ? _womenPortraits
      : female == false
          ? _menPortraits
          : (_stableHash(seed).isEven ? _womenPortraits : _menPortraits);
  return pool[_stableHash(seed) % pool.length];
}

/// Wide cover / casting banner.
String coverUrl(String seed) => _covers[_stableHash('cover-$seed') % _covers.length];

/// Square logo / thumbnail.
String squareUrl(String seed) => _squares[_stableHash('sq-$seed') % _squares.length];
